"""Generate the sandbox-safe locale catalog. No game files or settings are changed."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "tools/release/locales.json"
DEST = ROOT / "files/isf/i18n/catalog.lua"


def render_settings():
    # Noita does not guarantee access to mod-local files in the settings VM.
    # Inline the same generated catalog and resolver; no runtime file load.
    template = (ROOT / "tools/release/settings.template.lua").read_text(encoding="utf-8")
    resolver = (ROOT / "files/isf/i18n.lua").read_text(encoding="utf-8")
    catalog_line = 'local catalog=dofile_once("mods/interesting_seed_filter/files/isf/i18n/catalog.lua")'
    assert catalog_line in resolver
    resolver = resolver.replace(catalog_line, "local catalog=(function()\n" + render() + "end)()")
    marker = 'local i18n=dofile_once("mods/interesting_seed_filter/files/isf/i18n.lua")'
    assert marker in template
    return "-- Generated by tools/release/generate_locales.py; edit settings.template.lua.\n" + template.replace(marker, "local i18n=(function()\n" + resolver + "\nend)()")


def render():
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    keys = source["keys"]
    assert len(keys) == len(set(keys))
    rows = ["-- Generated by tools/release/generate_locales.py; edit locales.json.\nreturn {\n"]
    for language, values in source["languages"].items():
        assert len(values) == len(keys), (language, len(values), len(keys))
        rows.append("  [" + json.dumps(language) + "]={\n")
        for key, value in zip(keys, values):
            assert value.strip(), (language, key)
            rows.append("    " + key + "=" + json.dumps(value, ensure_ascii=False) + ",\n")
        rows.append("  },\n")
    return "".join(rows) + "}\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    settings = render_settings()
    if args.check:
        assert DEST.read_text(encoding="utf-8") == text, "Locale catalog is stale"
        assert (ROOT / "settings.lua").read_text(encoding="utf-8") == settings, "Settings localization is stale"
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(text, encoding="utf-8", newline="\n")
        (ROOT / "settings.lua").write_text(settings, encoding="utf-8", newline="\n")
    print("Locale catalog: 11 complete languages")


if __name__ == "__main__":
    main()
