"""Build a playable mod from source and a locally owned Noita data.wak.

Uses only Python's standard library. Extracted game images and their generated
Lua byte bundle stay in the ignored build output, outside the open-source tree.
"""
import argparse
import hashlib
import json
import re
import shutil
import struct
import zipfile
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[2]
MOD_ID = "interesting_seed_filter"


def read_wak(path):
    blob = path.read_bytes()
    if len(blob) < 16:
        raise ValueError("Invalid WAK header")
    _, count, _, _ = struct.unpack_from("<IIII", blob)
    entries = {}
    cursor = 16
    for _ in range(count):
        offset, size, length = struct.unpack_from("<III", blob, cursor)
        cursor += 12
        name = blob[cursor:cursor + length].decode("utf-8")
        cursor += length
        if cursor > len(blob) or offset + size > len(blob):
            raise ValueError("WAK entry out of bounds: " + name)
        entries[name] = (offset, size)
    return blob, entries


def source_paths():
    paths = [ROOT / name for name in ("init.lua", "settings.lua", "mod.xml", "LICENSE", "README.md", "workshop.xml", "workshop_preview_image.png")]
    for path in sorted((ROOT / "files").rglob("*")):
        if not path.is_file():
            continue
        relative = path.relative_to(ROOT).as_posix()
        if relative.startswith("files/isf/worldgen/data/") and (path.suffix == ".png" or path.name == "png_bytes.lua"):
            continue
        paths.append(path)
    paths += sorted((ROOT / "tools/foundation/diagnostics").glob("*.lua"))
    return paths


def build(wak, output):
    if output.exists():
        raise FileExistsError("Use a fresh output folder: " + str(output))
    manifest = json.loads((ROOT / "tools/release/game_assets.json").read_text(encoding="utf-8"))
    blob, entries = read_wak(wak)
    assets = []
    # Verify every required file before creating the output directory.
    for row in manifest:
        offset, size = entries[row["source"]]
        data = blob[offset:offset + size]
        if hashlib.sha256(data).hexdigest() != row["sha256"]:
            raise ValueError("Unsupported game asset version: " + row["source"])
        assets.append((row["path"], data))
    for source in source_paths():
        target = output / source.relative_to(ROOT)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
    for relative, data in assets:
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    lines = ["-- Generated by tools/worldgen/generate_png_bytes.py; do not edit.\nreturn {\n"]
    for relative, data in assets:
        encoded = "".join(f"\\{value:03d}" for value in data)
        lines.append(f'  ["mods/{MOD_ID}/{relative}"]="{encoded}",\n')
    (output / "files/isf/worldgen/data/png_bytes.lua").write_text("".join(lines) + "}\n", encoding="ascii", newline="\n")
    notice = (ROOT / "docs/THIRD_PARTY_NOTICES.md").read_text(encoding="utf-8")
    (output / "THIRD_PARTY_NOTICES.txt").write_text(notice, encoding="utf-8", newline="\n")
    (output / "LICENSE.txt").write_text((ROOT / "LICENSE").read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    ElementTree.parse(output / "mod.xml")
    ElementTree.parse(output / "workshop.xml")
    for path in output.rglob("*.lua"):
        text = path.read_text(encoding="utf-8")
        for dependency in re.findall(r'''["']mods/interesting_seed_filter/([^"'\n]+\.lua)["']''', text):
            if dependency.startswith(".scratch/"):
                continue  # Read-only optional diagnostic markers are deliberately absent.
            if not (output / dependency).is_file():
                raise ValueError(f"Missing dependency in {path}: {dependency}")
    archive = output.parent / "Mimick-Rabbitfoot-1.0.0.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as stream:
        for path in sorted(output.rglob("*")):
            if path.is_file():
                stream.write(path, MOD_ID + "/" + path.relative_to(output).as_posix())
    with zipfile.ZipFile(archive) as stream:
        assert stream.testzip() is None
    print(f"Built {len(assets)} verified game assets and all runtime dependencies")
    print(output)
    print(archive)
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--wak", required=True, type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "dist" / MOD_ID)
    args = parser.parse_args()
    build(args.wak.resolve(), args.out.resolve())
